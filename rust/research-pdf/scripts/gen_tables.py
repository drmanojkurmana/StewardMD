#!/usr/bin/env python3
"""Generate src/tables.rs from pdfminer.six's data tables, so the Rust reader
decodes text exactly as pdfplumber (which uses pdfminer.six) does:

- Adobe Glyph List (glyph name -> Unicode)
- Standard, MacRoman, WinAnsi and PDFDoc encodings
- metrics (descent, ascent, widths) of the standard 14 fonts and their aliases

    python3 rust/research-pdf/scripts/gen_tables.py > rust/research-pdf/src/tables.rs
"""
import pdfminer
from pdfminer.encodingdb import EncodingDB
from pdfminer.fontmetrics import FONT_METRICS
from pdfminer.glyphlist import glyphname2unicode


def rs(s: str) -> str:
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in s) + '"'


print(f"// @generated by scripts/gen_tables.py from pdfminer.six {pdfminer.__version__}. Do not edit.")
print("// Glyph list: Adobe Glyph List (BSD-3-Clause). Font metrics: Adobe AFM files")
print("// (redistribution permitted, see pdfminer/fontmetrics.py).")
print("#![allow(clippy::all)]")
print()
names = sorted(glyphname2unicode.items())
print(f"pub static GLYPHS: [(&str, &str); {len(names)}] = [")
for k, v in names:
    print(f"    ({rs(k)}, {rs(v)}),")
print("];")
for enc in ["StandardEncoding", "MacRomanEncoding", "WinAnsiEncoding", "PDFDocEncoding"]:
    m = EncodingDB.encodings[enc]
    arr = ["\"\""] * 256
    for code, ch in m.items():
        arr[code] = rs(ch)
    const = enc.replace("Encoding", "").upper()
    print(f"pub static ENC_{const}: [&str; 256] = [{', '.join(arr)}];")
print()
print("pub struct Std14 { pub name: &'static str, pub ascent: f64, pub descent: f64, pub bbox: [f64; 4], pub widths: &'static [(&'static str, f64)] }")
print(f"pub static STD14: [Std14; {len(FONT_METRICS)}] = [")
for name, (desc, widths) in sorted(FONT_METRICS.items()):
    w = ", ".join(f"({rs(k)}, {float(v)!r})" for k, v in sorted(widths.items()))
    bb = ", ".join(repr(float(x)) for x in desc.get("FontBBox", (0, 0, 0, 0)))
    print(f"    Std14 {{ name: {rs(name)}, ascent: {float(desc.get('Ascent', 0))!r}, descent: {float(desc.get('Descent', 0))!r}, bbox: [{bb}], widths: &[{w}] }},")
print("];")
