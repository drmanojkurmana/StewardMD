"""Cross-language tests for the worker IPD decryption seam (5C.2).

The vector is generated by test/fixtures/research/ipd/make-vector.mjs using
_ipd.js's own encryptSnapshot with a fixed TEST KEK (a committed fixture,
not a production secret). These tests prove the Python worker decrypts
exactly what the API encrypts, that a wrong KEK or tampered bytes fail
cleanly with stable codes, and that a stats_model job runs end to end on
an encrypted snapshot while plaintext never leaves memory (result.json
carries aggregates only, and nothing else is ever written to storage).
"""
from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

import pytest

import research_worker.jobs as worker_jobs
from stats import ipd_crypto
from stats import job as stats_job

VECTOR_PATH = (
    Path(__file__).resolve().parents[3]
    / "test" / "fixtures" / "research" / "ipd" / "vector.json"
)
VECTOR = json.loads(VECTOR_PATH.read_text(encoding="utf-8"))
KEK = VECTOR["kek"]
PLAINTEXT = VECTOR["plaintextCsv"].encode("utf-8")
CIPHERTEXT = base64.b64decode(VECTOR["ciphertextB64"])
ENVELOPE = VECTOR["envelope"]

R2_KEY = "projects/p1/data/snapshots/ipd_vec1.csv"
RESULT_KEY = "projects/p1/jobs/job_1/result.json"
SECRET = "test-secret"


class FakeStorage:
    def __init__(self, objects=None):
        self.objects = dict(objects or {})
        self.writes = []

    def get_bytes(self, key):
        return self.objects.get(key)

    def exists(self, key):
        return key in self.objects

    def put_bytes(self, key, data, content_type="application/json"):
        self.objects[key] = data
        self.writes.append(key)


def make_msg(**over):
    msg = {
        "v": 1,
        "kind": "stats_model",
        "jobId": "job_1",
        "projectId": "p1",
        "idempotencyKey": "k1",
        "createdAt": 1763900000,
        "input": {
            "r2Key": R2_KEY,
            "model": {"family": "linear", "formula": "y ~ x"},
            "compliance": {"ipdApproved": True, "evidenceId": "irb-2026-001"},
            "envelope": dict(ENVELOPE),
        },
        "ceilings": {"maxSeconds": 240, "maxRows": 100000},
    }
    msg.update(over)
    return msg


def flipped(data: bytes, index: int) -> bytes:
    return data[:index] + bytes([data[index] ^ 0x01]) + data[index + 1:]


@pytest.fixture
def callbacks(monkeypatch):
    sent = []

    def fake_send(client, base_url, job_id, payload, secret, *, sleep=None, now=None):
        sent.append(payload)
        return True

    monkeypatch.setattr(worker_jobs, "send_callback", fake_send)
    return sent


@pytest.fixture
def kek_env(monkeypatch):
    monkeypatch.setenv(ipd_crypto.KEK_ENV, KEK)


def run(msg, storage, **kw):
    return stats_job.run_job(
        msg, storage=storage, callback_client=None,
        callback_url="https://stewardmd.in", secret=SECRET, **kw,
    )


# ---- ipd_crypto: byte compatibility with _ipd.js ------------------------------


def test_vector_decrypts_byte_exact():
    out = ipd_crypto.decrypt_snapshot(ENVELOPE, CIPHERTEXT, kek_secret=KEK)
    assert out == PLAINTEXT
    assert hashlib.sha256(out).hexdigest() == VECTOR["plaintextSha256"]


def test_kek_from_env(monkeypatch):
    monkeypatch.setenv(ipd_crypto.KEK_ENV, KEK)
    assert ipd_crypto.decrypt_snapshot(ENVELOPE, CIPHERTEXT) == PLAINTEXT


def test_wrong_kek_fails_cleanly():
    with pytest.raises(ipd_crypto.IpdCryptoError) as ei:
        ipd_crypto.decrypt_snapshot(ENVELOPE, CIPHERTEXT, kek_secret="wrong-kek-0123456789abcdef")
    assert ei.value.code == "ipd_decrypt_failed"
    assert str(ei.value) == "ipd_decrypt_failed"  # no detail, no key material


@pytest.mark.parametrize("secret", [None, "", "short"])
def test_missing_or_short_kek(monkeypatch, secret):
    monkeypatch.delenv(ipd_crypto.KEK_ENV, raising=False)
    with pytest.raises(ipd_crypto.IpdCryptoError) as ei:
        ipd_crypto.decrypt_snapshot(ENVELOPE, CIPHERTEXT, kek_secret=secret)
    assert ei.value.code == "ipd_kek_unconfigured"


def test_tampered_ciphertext_fails_cleanly():
    for index in (0, len(CIPHERTEXT) // 2, len(CIPHERTEXT) - 1):  # body and GCM tag
        with pytest.raises(ipd_crypto.IpdCryptoError) as ei:
            ipd_crypto.decrypt_snapshot(ENVELOPE, flipped(CIPHERTEXT, index), kek_secret=KEK)
        assert ei.value.code == "ipd_decrypt_failed"


def test_tampered_wrapped_key_fails_cleanly():
    wrapped = bytearray(base64.b64decode(ENVELOPE["wrappedKey"]))
    wrapped[0] ^= 0x01
    bad = dict(ENVELOPE, wrappedKey=base64.b64encode(bytes(wrapped)).decode())
    with pytest.raises(ipd_crypto.IpdCryptoError) as ei:
        ipd_crypto.decrypt_snapshot(bad, CIPHERTEXT, kek_secret=KEK)
    assert ei.value.code == "ipd_decrypt_failed"


def test_tampered_iv_fails_cleanly():
    iv = bytearray(base64.b64decode(ENVELOPE["iv"]))
    iv[0] ^= 0x01
    bad = dict(ENVELOPE, iv=base64.b64encode(bytes(iv)).decode())
    with pytest.raises(ipd_crypto.IpdCryptoError) as ei:
        ipd_crypto.decrypt_snapshot(bad, CIPHERTEXT, kek_secret=KEK)
    assert ei.value.code == "ipd_decrypt_failed"


@pytest.mark.parametrize("bad", [
    None,
    [],
    dict(ENVELOPE, alg="AES-128-GCM"),
    dict(ENVELOPE, wrap="AES-KWP"),
    dict(ENVELOPE, iv="!!!not-base64!!!"),
    dict(ENVELOPE, iv=base64.b64encode(b"short").decode()),
    dict(ENVELOPE, wrappedKey=base64.b64encode(b"short").decode()),
])
def test_validate_envelope_rejects_malformed(bad):
    with pytest.raises(ValueError):
        ipd_crypto.validate_envelope(bad)


# ---- stats_model job on the encrypted vector ----------------------------------


def test_stats_job_end_to_end_on_encrypted_snapshot(callbacks, kek_env):
    storage = FakeStorage({R2_KEY: CIPHERTEXT})
    out = run(make_msg(), storage)
    assert out == {"status": "done", "settled": True, "skipped": False, "error": None}
    stored = json.loads(storage.objects[RESULT_KEY])
    assert stored["status"] == "done"
    assert stored["family"] == "linear"
    assert stored["manifest"]["dataHash"]
    assert stored["manifest"]["n"] == 8
    # aggregates only: plaintext never leaves memory
    assert PLAINTEXT not in storage.objects[RESULT_KEY]
    assert "café".encode("utf-8") not in storage.objects[RESULT_KEY]
    assert "columns" not in stored and "rows" not in stored
    assert storage.writes == [RESULT_KEY]  # nothing else ever written
    assert callbacks[0]["status"] == "done"
    assert callbacks[0]["resultKey"] == RESULT_KEY


def test_refuses_without_flag_before_any_decryption(callbacks, kek_env, monkeypatch):
    def no_decrypt(*a, **k):
        pytest.fail("decryption attempted without the compliance flag")

    monkeypatch.setattr(ipd_crypto, "decrypt_snapshot", no_decrypt)
    for compliance in (
        {"ipdApproved": False, "evidenceId": "irb-2026-001"},
        {"ipdApproved": True},
        {"ipdApproved": True, "evidenceId": ""},
    ):
        msg = make_msg()
        msg["input"]["compliance"] = compliance
        storage = FakeStorage({R2_KEY: CIPHERTEXT})
        out = run(msg, storage)
        assert out["status"] == "failed" and out["error"] == "ipd_gate"
        assert RESULT_KEY not in storage.objects
        assert storage.writes == []


def test_wrong_kek_fails_job(callbacks, monkeypatch):
    monkeypatch.setenv(ipd_crypto.KEK_ENV, "wrong-kek-0123456789abcdef")
    storage = FakeStorage({R2_KEY: CIPHERTEXT})
    out = run(make_msg(), storage)
    assert out["status"] == "failed" and out["error"] == "ipd_decrypt_failed"
    assert callbacks[0]["error"] == "ipd_decrypt_failed"
    assert RESULT_KEY not in storage.objects


def test_tampered_ciphertext_fails_job(callbacks, kek_env):
    storage = FakeStorage({R2_KEY: flipped(CIPHERTEXT, len(CIPHERTEXT) // 2)})
    out = run(make_msg(), storage)
    assert out["status"] == "failed" and out["error"] == "ipd_decrypt_failed"
    assert RESULT_KEY not in storage.objects


def test_kek_unconfigured_fails_job(callbacks, monkeypatch):
    monkeypatch.delenv(ipd_crypto.KEK_ENV, raising=False)
    storage = FakeStorage({R2_KEY: CIPHERTEXT})
    out = run(make_msg(), storage)
    assert out["status"] == "failed" and out["error"] == "ipd_kek_unconfigured"
    assert RESULT_KEY not in storage.objects


def test_validate_message_checks_envelope():
    stats_job.validate_message(make_msg())
    msg = make_msg()
    msg["input"]["envelope"] = dict(ENVELOPE, iv=base64.b64encode(b"short").decode())
    with pytest.raises(ValueError):
        stats_job.validate_message(msg)


def test_plaintext_path_unchanged(callbacks, kek_env):
    msg = make_msg()
    del msg["input"]["envelope"]
    storage = FakeStorage({R2_KEY: PLAINTEXT})
    out = run(msg, storage)
    assert out["status"] == "done" and out["error"] is None


def test_idempotent_replay_needs_no_kek(callbacks, monkeypatch):
    monkeypatch.setenv(ipd_crypto.KEK_ENV, KEK)
    storage = FakeStorage({R2_KEY: CIPHERTEXT})
    assert run(make_msg(), storage)["status"] == "done"
    # rerun with the KEK removed: the stored result settles without decryption
    monkeypatch.delenv(ipd_crypto.KEK_ENV)
    out = run(make_msg(), storage)
    assert out["skipped"] is True and out["status"] == "done"
