"""Phase 5D R parity: backend/research/stats against lm/glm (mtcars),
survival::survfit/survdiff/coxph/cox.zph (lung) and mada::reitsma/sroc
(AuditC, Dementia).

Compares against test/fixtures/research/parity-5d.json, generated by
scripts/research-parity-5d.R (R + survival + mada). The JSON is gitignored
and never faked: when absent this file SKIPS with a message saying how to
generate it. Numeric gate (plan section 12): abs diff <= 1e-4 OR rel diff
<= 1e-4; p-values below 1e-6 only pin the order of magnitude.

Run: cd backend/research && .venv/bin/python -m pytest tests/test_stats_parity.py
"""
from __future__ import annotations

import json
import math
