PARITY_PATH = Path(__file__).resolve().parents[3] / "test" / "fixtures" / "research" / "parity-5d.json"
COMPLIANCE = {"ipdApproved": True, "evidenceId": "parity-fixture-public-data"}


def close(actual, expected, label):
    assert actual is not None, f"{label}: got None, want {expected}"
    abs_diff = abs(actual - expected)
    rel = abs_diff / max(1e-12, abs(expected))
    assert abs_diff <= 1e-4 or rel <= 1e-4, (
        f"{label}: got {actual}, want {expected} (abs {abs_diff}, rel {rel})"
    )


def close_p(actual, expected, label):
    if expected < 1e-6:
        assert actual < 1e-6, f"{label}: p stays tiny, got {actual}"
    else:
        close(actual, expected, label)


def null_or_close(actual, expected, label):
    if expected is None:
        assert actual is None, f"{label}: want null, got {actual}"
    else:
        close(actual, expected, label)


if not PARITY_PATH.exists():
    def test_parity_5d_skipped():
        pytest.skip(
            "parity-5d.json is absent: generate it with "
            "`R_LIBS_USER=~/Library/R/library Rscript scripts/research-parity-5d.R` "
            "(needs R + survival + mada; see the parity-5d job in "
            ".github/workflows/research-ci.yml). It is never committed and never faked."
        )
else:
    PARITY = json.loads(PARITY_PATH.read_text())

    def test_meta_records_pinned_calls_and_tolerance():
        meta = PARITY["meta"]
        assert meta["tolerance"] == {"abs": 1e-4, "rel": 1e-4}
        assert meta["level"] == 0.95
        calls = meta["referenceCalls"]
        assert 'ties = "efron"' in calls["coxph"]
        assert 'transform = "km"' in calls["cox_zph"]
        assert "correction" in calls["reitsma"] and "REML" in calls["reitsma"]
        assert 'conf.type = "log"' in calls["survfit"]

    def test_regression_linear_matches_lm():
        ref = PARITY["regression"]
        cols = ref["columns"]
        res = linear_regression(cols, ref["linear"]["formula"], compliance=COMPLIANCE)
        exp = ref["linear"]
        assert res["n"] == exp["n"]
        assert res["dfResidual"] == exp["dfResidual"]
        assert len(res["coefficients"]) == len(exp["coefficients"])
        for got, want in zip(res["coefficients"], exp["coefficients"]):
            assert got["term"] == want["term"]
            close(got["estimate"], want["est"], f"lm {want['term']} estimate")
            close(got["se"], want["se"], f"lm {want['term']} se")
            close(got["t"], want["t"], f"lm {want['term']} t")
            close_p(got["p"], want["p"], f"lm {want['term']}")
            close(got["ciLower"], want["lo"], f"lm {want['term']} ciLower")
            close(got["ciUpper"], want["hi"], f"lm {want['term']} ciUpper")
        close(res["sigma"], exp["sigma"], "lm sigma")
        close(res["r2"], exp["r2"], "lm R2")
        close(res["aic"], exp["aic"], "lm AIC")

    def test_regression_hc3_matches_hat_matrix_formula():
        ref = PARITY["regression"]
        res = linear_regression(
            ref["columns"], ref["linear"]["formula"], compliance=COMPLIANCE, robust="HC3"
        )
        for got, want in zip(res["coefficients"], ref["linear"]["hc3Se"]):
            close(got["se"], want, f"HC3 {got['term']} se")

    def test_regression_logistic_matches_glm_binomial():
        ref = PARITY["regression"]
        res = logistic_regression(ref["columns"], ref["logistic"]["formula"], compliance=COMPLIANCE)
        exp = ref["logistic"]
        assert res["n"] == exp["n"]
        for got, want in zip(res["coefficients"], exp["coefficients"]):
            assert got["term"] == want["term"]
            close(got["estimate"], want["est"], f"glm {want['term']} estimate")
            close(got["se"], want["se"], f"glm {want['term']} se")
            close(got["z"], want["z"], f"glm {want['term']} z")
            close_p(got["p"], want["p"], f"glm {want['term']}")
            close(got["ciLower"], want["lo"], f"glm {want['term']} ciLower")
            close(got["ciUpper"], want["hi"], f"glm {want['term']} ciUpper")
        close(res["aic"], exp["aic"], "glm AIC")
        close(res["deviance"], exp["deviance"], "glm deviance")
        close(res["nullDeviance"], exp["nullDeviance"], "glm null deviance")

    def _lung():
        rows = PARITY["survival"]["rows"]
        t = [r["time"] for r in rows]
        e = [1.0 if r["status"] == 2 else 0.0 for r in rows]
        return rows, t, e

    def test_survival_km_matches_survfit():
        rows, t, e = _lung()
        res = kaplan_meier(t, e, compliance=COMPLIANCE)
        exp = PARITY["survival"]["km"]
        assert res["n"] == exp["n"]
        assert res["events"] == exp["events"]
        assert len(res["steps"]) == len(exp["steps"])
        for got, want in zip(res["steps"], exp["steps"]):
            label = f"KM t={want['time']}"
            assert got["time"] == want["time"], f"{label}: time exact"
            assert got["nRisk"] == want["nRisk"], f"{label}: nRisk exact"
            assert got["nEvent"] == want["nEvent"], f"{label}: nEvent exact"
            assert got["nCensor"] == want["nCensor"], f"{label}: nCensor exact"
            close(got["surv"], want["surv"], f"{label} surv")
            close(got["se"], want["se"], f"{label} Greenwood se(log S)")
            null_or_close(got["ciLower"], want["lo"], f"{label} ciLower")
            null_or_close(got["ciUpper"], want["hi"], f"{label} ciUpper")
        for key, ref_key in (("median", "median"), ("medianCiLower", "medianLo"), ("medianCiUpper", "medianHi")):
            if exp[ref_key] is None:
                assert res[key] is None, f"{key} null"
            else:
                assert res[key] == exp[ref_key], f"{key} exact (event time)"

    def test_survival_logrank_matches_survdiff():
        rows, t, e = _lung()
        group = [r["sex"] for r in rows]
        res = log_rank(t, e, group, compliance=COMPLIANCE)
        exp = PARITY["survival"]["logrank"]
        assert res["df"] == exp["df"]
        close(res["chisq"], exp["chisq"], "logrank chisq")
        close_p(res["p"], exp["p"], "logrank")
        assert len(res["groups"]) == len(exp["groups"])
        for got, want in zip(res["groups"], exp["groups"]):
            assert got["group"] == want["group"]
            assert got["n"] == want["n"]
            close(got["observed"], want["observed"], f"logrank group {want['group']} observed")
            close(got["expected"], want["expected"], f"logrank group {want['group']} expected")

    def test_survival_cox_matches_coxph_efron():
        rows, t, e = _lung()
        cov = {"age": [r["age"] for r in rows], "sex": [r["sex"] for r in rows]}
        res = cox_ph(t, e, cov, compliance=COMPLIANCE)
        exp = PARITY["survival"]["cox"]
        assert res["ties"] == "efron"
        assert res["n"] == exp["n"]
        assert res["events"] == exp["events"]
        close(res["logLik"], exp["logLik"], "cox partial logLik")
        for got, want in zip(res["coefficients"], exp["coefficients"]):
            assert got["term"] == want["term"]
            close(got["coef"], want["coef"], f"cox {want['term']} coef")
            close(got["se"], want["se"], f"cox {want['term']} se")
            close(got["z"], want["z"], f"cox {want['term']} z")
            close_p(got["p"], want["p"], f"cox {want['term']}")
            close(got["hr"], want["hr"], f"cox {want['term']} HR")
            close(got["hrCiLower"], want["lo"], f"cox {want['term']} HR ciLower")
            close(got["hrCiUpper"], want["hi"], f"cox {want['term']} HR ciUpper")

    def test_survival_ph_test_matches_cox_zph_km():
        rows, t, e = _lung()
        cov = {"age": [r["age"] for r in rows], "sex": [r["sex"] for r in rows]}
        res = cox_ph(t, e, cov, compliance=COMPLIANCE)
        exp = PARITY["survival"]["ph"]
        assert res["phTest"]["transform"] == exp["transform"] == "km"
        for got, want in zip(res["phTest"]["terms"], exp["terms"]):
            assert got["term"] == want["term"]
            assert got["df"] == want["df"]
            close(got["chisq"], want["chisq"], f"zph {want['term']} chisq")
            close_p(got["p"], want["p"], f"zph {want['term']}")
        g = res["phTest"]["global"]
        assert g["df"] == exp["global"]["df"]
        close(g["chisq"], exp["global"]["chisq"], "zph GLOBAL chisq")
        close_p(g["p"], exp["global"]["p"], "zph GLOBAL")

    @pytest.mark.parametrize("case_index", [0, 1])
    def test_diagnostic_matches_mada_reitsma(case_index):
        case = PARITY["diagnostic"]["datasets"][case_index]
        studies = case["studies"]
        ps = per_study_accuracy(studies, compliance=COMPLIANCE)
        assert ps["correctionApplied"] == case["correctionApplied"]
        for got, want in zip(ps["studies"], case["perStudy"]):
            assert got["id"] == want["id"]
            close(got["sens"], want["sens"], f"{case['name']} {want['id']} sens")
            close(got["spec"], want["spec"], f"{case['name']} {want['id']} spec")
        res = reitsma(studies, compliance=COMPLIANCE)
        exp = case["reitsma"]
        assert res["k"] == len(studies)
        for got, want in zip(res["coefficients"], exp["coefficients"]):
            assert got["term"] == want["term"]
            close(got["estimate"], want["est"], f"{case['name']} {want['term']} estimate")
            close(got["se"], want["se"], f"{case['name']} {want['term']} se")
            close(got["z"], want["z"], f"{case['name']} {want['term']} z")
            close_p(got["p"], want["p"], f"{case['name']} {want['term']}")
            close(got["ciLower"], want["lo"], f"{case['name']} {want['term']} ciLower")
            close(got["ciUpper"], want["hi"], f"{case['name']} {want['term']} ciUpper")
        for i in range(2):
            for j in range(2):
                close(res["psi"][i][j], exp["psi"][i][j], f"{case['name']} Psi[{i},{j}]")
        close(res["pooledSens"], exp["pooledSens"], f"{case['name']} pooled sens")
        close(res["pooledFpr"], exp["pooledFpr"], f"{case['name']} pooled FPR")
        close(res["pooledSpec"], exp["pooledSpec"], f"{case['name']} pooled spec")
        sroc = res["sroc"]
        assert len(sroc["fpr"]) == len(case["sroc"]["fpr"])
        for got, want in zip(sroc["fpr"], case["sroc"]["fpr"]):
            close(got, want, f"{case['name']} sroc fpr grid")
        for kind in ("ruttergatsonis", "naive"):
            assert sroc[kind] is not None
            for got, want in zip(sroc[kind], case["sroc"][kind]):
                close(got, want, f"{case['name']} SROC {kind}")