#!/usr/bin/env node
/* KnowYourIQ importance data compiler.
 * Reads the chapter-yield file (~/prep-data/assessment/external/dreampg/chapter-yield.json,
 * third-party, inferred from past papers, NOT official) and the bank manifest, and writes
 * prep-knowyouriq-data.js: DERIVED subject-level weights only.
 *
 * The yield file's own licence line says internal prioritisation, do not republish, so the
 * output carries no chapter names, no ranks and no source string: per exam, one number per
 * bank subject. Formula (also in prep-coach.js):
 *   score(subject) = SUM over its chapters of TIER_W[chapter.tier], then min-max to 0..1.
 *   TIER_W: Diamond 4, Gold 3, Silver 2, Bronze 1 (the file's own tiers, NOT KnowYourIQ tiers).
 * Bank weight: subject item count, min-max to 0..1 across subjects.
 * Subjects with no yield rows (e.g. ss-*) are absent: the coach treats absence as neutral
 * and says so on screen.
 *
 * Usage: node scripts/compile-knowyouriq.mjs [--check]  (--check: verify the committed
 * file is fresh instead of writing it).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(ROOT, "prep-knowyouriq-data.js");
const YIELD = path.join(process.env.HOME || "~", "prep-data/assessment/external/dreampg/chapter-yield.json");
const MANIFEST = path.join(ROOT, "prep/bank/v5/manifest.json");

// The yield file's short subject labels -> bank subject ids. Anything unmapped is dropped and reported.
const SUBJ = {
  Anaes: "anaesthesia", Anatomy: "anatomy", Biochemistry: "biochemistry", ENT: "ent", FM: "forensic-medicine",
  Medicine: "medicine", Micro: "microbiology", OG: "obstetrics-gynaecology", Ophthal: "ophthalmology",
  Ortho: "orthopaedics", Patho: "pathology", Pediatrics: "paediatrics", Pharm: "pharmacology",
  Physiology: "physiology", Psychiatry: "psychiatry", Radiology: "radiology", SPM: "community-medicine",
  Skin: "dermatology", Surgery: "surgery",
};
const EXAMS = { "neet-pg-2024": "neet-pg", "inicet-2023": "ini-cet" };
const TIER_W = { Diamond: 4, Gold: 3, Silver: 2, Bronze: 1 };

const mm = (scores) => {
  const vs = Object.values(scores);
  if (!vs.length) return {};
  const lo = Math.min(...vs), hi = Math.max(...vs), span = hi - lo || 1;
  const out = {};
  for (const k of Object.keys(scores)) out[k] = Math.round(((scores[k] - lo) / span) * 100) / 100;
  return out;
};

function compile() {
  const y = JSON.parse(fs.readFileSync(YIELD, "utf8"));
  const exams = {}, unmapped = new Set();
  let chapters = 0;
  for (const [src, exam] of Object.entries(EXAMS)) {
    const rows = (y[src] && y[src].rows) || [];
    const scores = {};
    for (const r of rows) {
      const id = SUBJ[r.subject];
      if (!id) { unmapped.add(String(r.subject)); continue; }
      scores[id] = (scores[id] || 0) + (TIER_W[r.tier] || 0);
      chapters++;
    }
    exams[exam] = mm(scores);
  }
  const m = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const bank = mm(Object.fromEntries(m.subjects.map((s) => [s.id, s.items])));
  return {
    v: 1,
    gen: new Date().toISOString().slice(0, 10),
    chapters,
    exams,
    bank,
    unmapped: [...unmapped].sort(),
    note: "Derived subject weights for KnowYourIQ exam importance (0..1, min-max). No chapter data ships: absent subjects use a neutral weight, labelled on screen.",
  };
}

function emit(d) {
  return "/* KnowYourIQ exam-importance data. GENERATED by scripts/compile-knowyouriq.mjs (" + d.gen + "); do not edit.\n" +
    "   Derived subject weights only (" + d.chapters + " yield chapters folded in, none shipped). ES5, window.PREP_KYIQ_DATA. */\n" +
    "(function (G) {\n  \"use strict\";\n  var DATA = " + JSON.stringify({ v: d.v, gen: d.gen, exams: d.exams, bank: d.bank, note: d.note }) + ";\n" +
    "  if (typeof module !== \"undefined\" && module.exports) module.exports = DATA;\n  if (G) G.PREP_KYIQ_DATA = DATA;\n})(typeof window !== \"undefined\" ? window : null);\n";
}

const data = compile();
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  const same = cur.replace(/^\/\* KnowYourIQ exam-importance data\. GENERATED.*?\n/, "GEN\n") ===
    emit(data).replace(/^\/\* KnowYourIQ exam-importance data\. GENERATED.*?\n/, "GEN\n");
  if (!same) { console.error("prep-knowyouriq-data.js is stale: run node scripts/compile-knowyouriq.mjs"); process.exit(1); }
  console.log("knowyouriq-data fresh (" + data.chapters + " chapters, unmapped: " + (data.unmapped.join(",") || "none") + ")");
} else {
  fs.writeFileSync(OUT, emit(data));
  console.log("wrote prep-knowyouriq-data.js (" + data.chapters + " chapters, unmapped: " + (data.unmapped.join(",") || "none") + ")");
}
