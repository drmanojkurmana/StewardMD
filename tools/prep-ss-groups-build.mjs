/* Resolves prep/ss-groups.json (the NEET-SS feeder-group -> super-specialty mapping) against the bank and
 * writes prep-ss-groups.js (window.PREP_SS_GROUPS, ES5, also require()-able), the single copy prep-plan.js reads.
 * (avoid star-slash inside this comment: it would close the block early)
 * Rule: medical-kind groups show own + medicalCore + biostatistics; surgical shows own + biostatistics; every other
 * group shows own + biostatistics. Subjects resolve in taxonomy order. Every mapped subject must exist in
 * prep/taxonomy.json; live counts come from the bank index files plus prep/bank/overlay-counts.json.
 * USAGE: node tools/prep-ss-groups-build.mjs [--check]   (--check: exit 1 when prep-ss-groups.js is not up to date) */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "prep/ss-groups.json");
const OUT = path.join(ROOT, "prep-ss-groups.js");

function taxonomyOrder() {
  const tax = JSON.parse(fs.readFileSync(path.join(ROOT, "prep/taxonomy.json"), "utf8"));
  const order = [];
  (tax.branches || []).forEach((b) => (b.subjects || []).forEach((s) => { if (s && s.id) order.push(s.id); }));
  return order;
}
function bankVersion(sid) {
  // Mirrors the app (prep.js VER/bvOf): v5 unless the taxonomy pins another bank version for the subject.
  try {
    const tax = JSON.parse(fs.readFileSync(path.join(ROOT, "prep/taxonomy.json"), "utf8"));
    for (const b of tax.branches || []) for (const s of b.subjects || []) if (s && s.id === sid && s.bv) return s.bv;
  } catch {}
  return "v5";
}
function liveCounts() {
  const counts = {};
  const idxFiles = [];
  for (const dir of fs.readdirSync(path.join(ROOT, "prep/bank"))) {
    const base = path.join(ROOT, "prep/bank", dir);
    let subs = [];
    try { subs = fs.readdirSync(base); } catch { continue; }
    for (const s of subs) {
      if (!s.startsWith("ss-") || dir !== bankVersion(s)) continue;
      const ix = path.join(base, s, "index.json");
      if (fs.existsSync(ix)) idxFiles.push([s, ix]);
    }
  }
  for (const [sid, ix] of idxFiles) {
    try {
      const d = JSON.parse(fs.readFileSync(ix, "utf8"));
      counts[sid] = (counts[sid] || 0) + ((d.topics || []).reduce((n, t) => n + (+t.count || 0), 0));
    } catch {}
  }
  try {
    const ov = JSON.parse(fs.readFileSync(path.join(ROOT, "prep/bank/overlay-counts.json"), "utf8"));
    for (const set of Object.values(ov.sets || {})) {
      for (const [sid, mods] of Object.entries(set || {})) {
        if (!String(sid).startsWith("ss-") || !mods || typeof mods !== "object") continue;
        counts[sid] = (counts[sid] || 0) + Object.values(mods).reduce((n, v) => n + (+v || 0), 0);
      }
    }
  } catch {}
  return counts;
}
export function resolve() {
  const src = JSON.parse(fs.readFileSync(SRC, "utf8"));
  const order = taxonomyOrder(), pos = {};
  order.forEach((id, i) => { pos[id] = i; });
  const known = new Set(order);
  const missing = [];
  for (const id of src.medicalCore.concat([src.biostatistics])) if (!known.has(id)) missing.push(id);
  for (const g of src.groups) for (const id of g.own) if (!known.has(id)) missing.push(g.id + ":" + id);
  if (missing.length) throw new Error("ss-groups subjects missing from taxonomy: " + missing.join(", "));
  const counts = liveCounts();
  const groups = src.groups.map((g) => {
    const want = new Set(g.own);
    if (g.kind === "medical") src.medicalCore.forEach((id) => want.add(id));
    want.add(src.biostatistics);
    const subjects = order.filter((id) => want.has(id));
    return { id: g.id, label: g.label, feeder: g.feeder, kind: g.kind, includes: g.includes, subjects };
  });
  return { v: src.v, groups, counts };
}
function emit(data) {
  const body = JSON.stringify({ v: data.v, groups: data.groups }, null, 1);
  return "/* GENERATED by tools/prep-ss-groups-build.mjs from prep/ss-groups.json. Do not edit by hand. ES5.\n" +
    "   window.PREP_SS_GROUPS = { v, groups: [{ id, label, feeder, kind, includes, subjects }] }; require() returns the same object. */\n" +
    "(function (G) {\n  \"use strict\";\n" +
    "  var NODE = typeof module !== \"undefined\" && module.exports && !(G && G.document);\n" +
    "  var DATA = " + body.split("\n").join("\n  ") + ";\n" +
    "  if (NODE) { module.exports = DATA; return; }\n" +
    "  G.PREP_SS_GROUPS = DATA;\n" +
    "})(typeof window !== \"undefined\" ? window : this);\n";
}
const data = resolve();
const js = emit(data);
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== js) { console.error("prep-ss-groups.js is stale: run node tools/prep-ss-groups-build.mjs"); process.exit(1); }
  console.log("prep-ss-groups.js up to date");
} else {
  fs.writeFileSync(OUT, js);
  console.log("wrote prep-ss-groups.js (" + js.length + " bytes)");
}
const zero = [];
for (const g of data.groups) for (const id of g.subjects) if (!(data.counts[id] > 0)) zero.push(g.id + ":" + id);
console.log("live ss subjects: " + Object.keys(data.counts).filter((k) => k.startsWith("ss-") && data.counts[k] > 0).length +
  "; mapped with zero questions: " + (zero.length ? zero.join(", ") : "none"));
