#!/usr/bin/env node
/* Builds prep-profiles.js (window.PREP_PROFILES, ES5, also require()-able) from the versioned exam profiles in
 * prep/assess/profiles/*.json. The JSON files are the single source of truth; prep-profiles.js is their one compiled copy,
 * read by the app (prep.js MOCKS, prep-assess.js, prep-tests.js), the Arena server (functions/_prep-arena.js SCHEMES)
 * and generation (functions/_prep-core.js EXAM_PROFILES). test/prep-assess.test.mjs fails when the copy is stale.
 * USAGE: node tools/prep-profiles-build.mjs [--check]   (--check: exit 1 when prep-profiles.js is not up to date) */
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "prep/assess/profiles");
const OUT = join(ROOT, "prep-profiles.js");
// Fixed order: the app's exam tabs, then the rest.
const ORDER = ["neet-pg", "ini-cet", "fmge", "neet-ss", "ini-ss", "usmle-step1"];

export function build() {
  const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, ""));
  const ids = ORDER.filter((id) => files.includes(id)).concat(files.filter((id) => !ORDER.includes(id)).sort());
  const profiles = {};
  for (const id of ids) profiles[id] = JSON.parse(fs.readFileSync(join(DIR, id + ".json"), "utf8"));
  const data = JSON.stringify({ v: 1, ids, profiles });
  return "/* GENERATED by tools/prep-profiles-build.mjs from prep/assess/profiles/*.json. Do not edit by hand. ES5.\n" +
    "   window.PREP_PROFILES = { v, ids, profiles: { <exam id>: profile } }; require() returns the same object. */\n" +
    "(function (G) {\n  \"use strict\";\n  var P = " + data + ";\n" +
    "  if (typeof module !== \"undefined\" && module.exports) module.exports = P;\n" +
    "  if (G) G.PREP_PROFILES = P;\n" +
    "})(typeof window !== \"undefined\" ? window : null);\n";
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const js = build();
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (cur !== js) { console.error("prep-profiles.js is stale: run node tools/prep-profiles-build.mjs"); process.exit(1); }
    console.log("prep-profiles.js up to date");
  } else { fs.writeFileSync(OUT, js); console.log("wrote prep-profiles.js (" + js.length + " bytes)"); }
}
