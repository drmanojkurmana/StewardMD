  function toCsv(rep, sectionIndex) {
    var sec = arr(rep.sections)[sectionIndex || 0];
    if (!sec) return "";
    function cell(v) { var t = s(v); return /[",\n]/.test(t) ? '"' + t.replace(/"/g, '""') + '"' : t; }
    return [arr(sec.columns).map(cell).join(",")]
      .concat(arr(sec.rows).map(function (r) { return arr(r).map(cell).join(","); })).join("\n");
  }

