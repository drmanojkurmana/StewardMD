  /* ── rendering ───────────────────────────────────────────────────────────────
   * Dumb on purpose: it turns the structure above into HTML and adds nothing. Anything a reader
   * sees was decided by a builder, which is tested. */
  function toHtml(rep, opts) {
    opts = opts || {};
    var h = ['<article class="pgl-report">'];
    h.push('<header class="pgl-rep-head"><h1>' + esc(rep.title) + "</h1>");
    if (rep.subtitle) h.push('<p class="pgl-rep-sub">' + esc(rep.subtitle) + "</p>");
    h.push('<dl class="pgl-rep-meta">');
    arr(rep.meta).forEach(function (m) { h.push("<dt>" + esc(m[0]) + "</dt><dd>" + esc(m[1]) + "</dd>"); });
    h.push("</dl></header>");
    if (rep.verification) {
      var v = rep.verification;
      h.push('<section class="pgl-rep-verif"><h2>Verification status</h2><p>' +
        esc(v.verified + " of " + v.total + " entries verified · " + v.submitted + " awaiting verification · " +
            v.returned + " returned · " + v.draft + " draft" + (v.amended ? " · " + v.amended + " amended (originals retained)" : "")) +
        "</p><p>" + esc(v.monthsAttested + " of " + v.monthsTotal + " months authenticated by the guide" +
          (v.monthsOverdue.length ? " · overdue: " + v.monthsOverdue.join(", ") : "")) + "</p>" +
        "<p>" + esc(v.signedWithRegistration + " of " + v.verified + " verified entries carry the signer's " +
          "medical registration number; " + v.withVerificationCode + " carry a scannable verification code.") + "</p>" +
        '<p class="pgl-rep-clause">' + esc(v.clause) + "</p></section>");
    }
    arr(rep.sections).forEach(function (sec) {
      if (sec.divider) { h.push('<h2 class="pgl-rep-divider">' + esc(sec.heading) + "</h2>"); return; }
      h.push('<section class="pgl-rep-sec"><h2>' + esc(sec.heading) + "</h2>");
      if (sec.provenance) {
        h.push('<p class="pgl-rep-prov">' + esc(sourceLabel(sec.provenance.source)) +
          (sec.provenance.clause ? " · " + esc(sec.provenance.clause) : "") + "</p>");
      }
      if (arr(sec.rows).length) {
        h.push('<div class="pgl-rep-scroll"><table><thead><tr>');
        arr(sec.columns).forEach(function (c) { h.push("<th>" + esc(c) + "</th>"); });
        h.push("</tr></thead><tbody>");
        arr(sec.rows).forEach(function (row) {
          h.push("<tr>");
          arr(row).forEach(function (cell) { h.push("<td>" + esc(cell) + "</td>"); });
          h.push("</tr>");
        });
        h.push("</tbody></table></div>");
      } else {
        h.push('<p class="pgl-rep-empty">Nothing recorded yet.</p>');
      }
      if (sec.note) h.push('<p class="pgl-rep-note">' + esc(sec.note) + "</p>");
      h.push("</section>");
    });
    h.push('<footer class="pgl-rep-foot"><p>' + esc(rep.disclaimer) + "</p></footer>");
    h.push("</article>");
    return h.join("");
  }

