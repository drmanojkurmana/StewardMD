/* StewardMD — compile the Harrison ENRICHMENT runtime artifact: kb/dist/kb.enrichment.js
 *
 * window.KB_ENRICHMENT = { version, byId: { <id>: { name, system, class, ...harrison fields } } }
 *
 * Surfaces the additive disease.enrichment.harrison knowledge (paraphrased,
 * page-cited) to the runtime so the UI can DISPLAY it. This is reference
 * KNOWLEDGE only — no treatment regimens/doses, no pharmacology (the Drug Index
 * stays the single pharmacology DB). Read-only display data; it does not feed
 * the scoring engine, so it cannot change the differential (golden stays green).
 *
 * USAGE: node kb/tools/build-kb-enrichment.mjs [kbVersion]
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const DZ = join(ROOT, "kb", "diseases");
const OUT = join(ROOT, "kb", "dist", "kb.enrichment.js");
const kbVersion = process.argv[2] || "1";

const byId = {};
let n = 0, enriched = 0;
for (const f of readdirSync(DZ).filter((x) => x.endsWith(".json"))) {
  const d = JSON.parse(readFileSync(join(DZ, f), "utf8"));
  n++;
  const h = d.enrichment && d.enrichment.harrison;
  if (!h) continue;
  enriched++;
  byId[d.id] = {
    name: d.name, system: d.system || null, class: d.class || null,
    source: h.source || "Harrison's Principles of Internal Medicine, 22e",
    pages: h.pages || null,
    clinicalPearls: h.clinicalPearls || [],
    pathophysiology: h.pathophysiology || null,
    additionalDifferentials: h.additionalDifferentials || [],
    infectionMimics: h.infectionMimics || [],
    nonInfectiousMimics: h.nonInfectiousMimics || [],
    additionalInvestigations: h.additionalInvestigations || [],
    redFlags: h.redFlags || [],
    prognosis: h.prognosis || null,
    pitfalls: h.pitfalls || [],
    severityClassification: h.severityClassification || null,
    references: h.references || [],
    crossLinks: h.crossLinks || [],
  };
}

// ---- merge REFERENCE-ONLY diseases (kb/reference/*.json) — the broader Harrison
// disease universe. These are KNOWLEDGE/reference entries only: searchable + shown
// with their Harrison reference, but NOT diagnostic candidates (no scoring model),
// so they never enter or perturb the differential. Existing diagnostic diseases
// (the 140, already in byId) are never overwritten. ----
const REF = join(ROOT, "kb", "reference");
let referenceAdded = 0;
if (existsSync(REF)) {
  for (const f of readdirSync(REF).filter((x) => x.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(REF, f), "utf8"));
    if (!d.id || byId[d.id]) continue;           // don't shadow a diagnostic disease
    const h = d.harrison || d.reference || {};   // `reference` = source-neutral key (Nelson/Parsons/etc.)
    byId[d.id] = {
      name: d.name, system: d.system || null, class: d.class || null, referenceOnly: true,
      aliases: d.aliases || [],   // carry synonyms into the search index (searchable by alias)
      chapter: d.chapter || null,
      source: h.source || "Harrison's Principles of Internal Medicine, 22e",
      pages: h.pages || (d.page ? "Harrison 22e p." + d.page : null),
      clinicalPearls: h.clinicalPearls || [],
      pathophysiology: h.pathophysiology || null,
      additionalDifferentials: h.additionalDifferentials || [],
      infectionMimics: h.infectionMimics || [],
      nonInfectiousMimics: h.nonInfectiousMimics || [],
      additionalInvestigations: h.additionalInvestigations || [],
      redFlags: h.redFlags || [],
      prognosis: h.prognosis || null,
      pitfalls: h.pitfalls || [],
      severityClassification: h.severityClassification || null,
      references: h.references || [],
      crossLinks: h.crossLinks || [],
    };
    referenceAdded++;
  }
}

mkdirSync(dirname(OUT), { recursive: true });
const payload = { version: kbVersion, diseases: n, enriched, referenceDiseases: referenceAdded, totalSearchable: Object.keys(byId).length, byId };
writeFileSync(OUT, "/* GENERATED by kb/tools/build-kb-enrichment.mjs — do not edit by hand. */\nwindow.KB_ENRICHMENT = " + JSON.stringify(payload) + ";\n");
console.log(`wrote ${OUT}`);
console.log(`diseases=${n} enriched=${enriched} referenceDiseases=${referenceAdded} totalSearchable=${Object.keys(byId).length}`);
