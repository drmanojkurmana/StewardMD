/* StewardMD KB T2-display — compile the clinical DISPLAY artifact: kb/dist/kb.clinical.js
 *
 * window.KB_CLINICAL = { version, syndromes:{id:{...display fields...}}, ddxNi:[{...}] }
 * Holds the EXACT clinical fields the stewardship page reads from SYNDROMES/DDX_NI
 * (captured verbatim from the live engine via JSON round-trip => byte-identical).
 * The engine rebuilds window.SYNDROMES / window.DDX_NI from this + kb.core at load,
 * so the runtime reads display data exclusively from the KB. Drugs are referenced
 * by composition only (the regimen text here is treatment guidance, not pharmacology
 * data — no Drug Index content is duplicated).
 *
 * USAGE: node kb/tools/build-kb-clinical.mjs <engine-tx.json> <engine-dump.json> <kbVersion>
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const tx = JSON.parse(readFileSync(process.argv[2] || join(process.env.CLAUDE_JOB_DIR || "/tmp", "engine-tx.json"), "utf8"));
const dump = JSON.parse(readFileSync(process.argv[3] || join(process.env.CLAUDE_JOB_DIR || "/tmp", "engine-dump.json"), "utf8"));
const kbVersion = process.argv[4] || "1";

// infective: exact display fields, ordered to MATCH the live SYNDROMES object key order
// (so an object-level comparison is also identical, not just per-field).
const syndromes = {};
for (const id of Object.keys(dump.syndromes)) {
  const d = dump.syndromes[id];      // name, system
  const s = tx.syndromes[id];        // clinical fields
  const o = {};
  o.id = id; o.name = d.name; o.system = d.system;
  o.decisionStatus = s.decisionStatus; o.decisionLabel = s.decisionLabel;
  o.toxicityFactors = s.toxicityFactors;
  o.pathogens = s.pathogens;
  o.firstLine = s.firstLine;
  o.alternatives = s.alternatives;
  o.coverageMatrix = s.coverageMatrix;
  o.stewardship = s.stewardship;
  o.investigations = s.investigations;
  o.deescalation = s.deescalation;
  o.references = s.references;
  o.regimens = s.regimens;
  o.antibioticRelevant = s.antibioticRelevant;
  syndromes[id] = o;
}

// non-infective: the full DDX_NI objects verbatim (pure data, no closures)
const ddxNi = (dump.ddx_ni || []).map((d) => JSON.parse(JSON.stringify(d)));

mkdirSync(join(ROOT, "kb", "dist"), { recursive: true });
const out = "/* GENERATED by kb/tools/build-kb-clinical.mjs — do not edit by hand. */\n" +
  "window.KB_CLINICAL = " + JSON.stringify({ version: kbVersion, syndromes, ddxNi }) + ";\n";
writeFileSync(join(ROOT, "kb", "dist", "kb.clinical.js"), out);
console.log(`kb.clinical.js: ${Object.keys(syndromes).length} infective + ${ddxNi.length} non-infective, ${(out.length / 1024).toFixed(1)} KB`);
