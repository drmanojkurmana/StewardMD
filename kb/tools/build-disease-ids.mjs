#!/usr/bin/env node
// build-disease-ids.mjs - write functions/_kb_disease_ids.js from the built enrichment bundles.
//
// The Clinical Bulletins API (functions/_bulletin_rules.js) accepts only disease ids the app can open,
// i.e. the keys of window.KB_ENRICHMENT.byId. Pages Functions cannot read kb/dist at runtime, so the
// id list is generated and checked in. test/bulletins.test.mjs fails if it drifts from kb/dist.
//
// Usage: node kb/tools/build-disease-ids.mjs [--check]
//   --check  exit 1 if the checked-in file differs from what would be written (no write)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'functions', '_kb_disease_ids.js');
const PARTS = ['kb.enrichment.js', 'kb.enrichment.2.js'].map((f) => join(ROOT, 'kb', 'dist', f));

export function loadDiseaseIds() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  for (const p of PARTS) {
    if (!existsSync(p)) throw new Error('missing ' + p);
    vm.runInContext(readFileSync(p, 'utf8'), sandbox, { filename: p });
  }
  const byId = (sandbox.window.KB_ENRICHMENT && sandbox.window.KB_ENRICHMENT.byId) || {};
  return Object.keys(byId).sort();
}

export function renderModule(ids) {
  return '/* GENERATED by kb/tools/build-disease-ids.mjs from kb/dist/kb.enrichment*.js - do not edit by hand.\n' +
    ' * Disease ids the app can open (KB_ENRICHMENT.byId keys). Used to validate Clinical Bulletin mappings. */\n' +
    'export const KB_DISEASE_IDS = Object.freeze(' + JSON.stringify(ids) + ');\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const ids = loadDiseaseIds();
  const text = renderModule(ids);
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('functions/_kb_disease_ids.js is stale: run node kb/tools/build-disease-ids.mjs'); process.exit(1); }
    console.log('disease ids up to date (' + ids.length + ')');
  } else {
    writeFileSync(OUT, text);
    console.log('wrote ' + OUT + ' (' + ids.length + ' ids)');
  }
}
