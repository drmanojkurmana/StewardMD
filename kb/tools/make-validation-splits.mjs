/* StewardMD - train / dev / test split of the gold validation cases (Phase 0 of
 * kb/validation/PLAN-DX-ABX-10.md). Writes kb/validation/splits.json.
 *
 * WHY: the engine is hand-tuned. Tuning against the same cases you score on inflates the score.
 *   train - look at failures and tune freely
 *   dev   - check a change generalises before it lands
 *   test  - phase gates only; do not read individual test failures while tuning
 * test/dx-heldout.json and test/dx-heldout-2.json (independent author, doctor-style text) are always test.
 *
 * HOW: stratified by condition (expected.acceptableIds[0]) so every condition with 3+ cases has
 * one case in test. Order within a condition is sha256(id), so the split is deterministic and does
 * not depend on file order. Existing assignments are KEPT (a split that moves when a case is added
 * leaks); only new ids are placed. --reset recomputes everything (never do this after tuning).
 *
 * USAGE: node kb/tools/make-validation-splits.mjs [--reset]
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const VAL = join(ROOT, "kb", "validation");
const OUT = join(VAL, "splits.json");
const RESET = process.argv.includes("--reset");

const cases = JSON.parse(readFileSync(join(VAL, "cases.json"), "utf8"));
for (const f of readdirSync(join(VAL, "cases")).filter((x) => x.endsWith(".json")).sort()) cases.push(JSON.parse(readFileSync(join(VAL, "cases", f), "utf8")));
const heldout = JSON.parse(readFileSync(join(ROOT, "test", "dx-heldout.json"), "utf8"))
  .concat(existsSync(join(ROOT, "test", "dx-heldout-2.json")) ? JSON.parse(readFileSync(join(ROOT, "test", "dx-heldout-2.json"), "utf8")) : []);

const prev = !RESET && existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")).splits || {} : {};
const splits = {};
const h = (s) => createHash("sha256").update(String(s)).digest("hex");

// group new (unassigned) gold cases by condition
const groups = {};
for (const c of cases) {
  if (prev[c.id]) { splits[c.id] = prev[c.id]; continue; }
  const k = String(((c.expected || {}).acceptableIds || [])[0] || "_none").toLowerCase();
  (groups[k] = groups[k] || []).push(c.id);
}
// count what each condition already has, so adding cases later tops up test/dev fairly
const have = {};
for (const c of cases) {
  const k = String(((c.expected || {}).acceptableIds || [])[0] || "_none").toLowerCase();
  const s = splits[c.id]; if (!s) continue;
  have[k] = have[k] || { train: 0, dev: 0, test: 0 }; have[k][s]++;
}
for (const k of Object.keys(groups)) {
  const ids = groups[k].sort((a, b) => (h(a) < h(b) ? -1 : 1));
  const cur = have[k] || { train: 0, dev: 0, test: 0 };
  const total = ids.length + cur.train + cur.dev + cur.test;
  const wantTest = total >= 3 ? Math.max(1, Math.round(total * 0.2)) : 0;
  const wantDev = total >= 4 ? Math.max(1, Math.round(total * 0.2)) : total === 2 ? 1 : 0;
  for (const id of ids) {
    let s = "train";
    if (cur.test < wantTest) s = "test"; else if (cur.dev < wantDev) s = "dev";
    cur[s]++; splits[id] = s;
  }
}
for (const c of heldout) splits[c.id] = "test";

const count = { train: 0, dev: 0, test: 0 };
Object.values(splits).forEach((s) => count[s]++);
writeFileSync(OUT, JSON.stringify({
  about: "Train/dev/test split for the gold cases + held-out set. Generated by kb/tools/make-validation-splits.mjs. Do not tune against test.",
  counts: count, splits,
}, null, 1) + "\n");
console.log("splits", count, "->", OUT);
